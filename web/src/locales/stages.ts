const names: Record<Locale, Record<number, string>> = { en, pl }

// stageName returns the stage worth showing, or "" for plain printing and idle.
export function stageName(stage: number, locale: string): string {
  if (stage <= 0 || stage === 255) {
    return ''
  }
  return names[locale as Locale]?.[stage] ?? `#${stage}`
}
